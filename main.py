class Queue:
    def __init__(self, maxsize=0):
        self.maxsize = maxsize
        self._queue = []
        self._evput = asyncio.Event()
        self._evget = asyncio.Event()

    def _get(self):
        self._evget.set()
        self._evget.clear()
        return self._queue.pop(0)

    async def get(self):
        while self.empty():
            await self._evput.wait()
        return self._get()

    def get_nowait(self):
        if self.empty():
            raise Exception("Cannot get item, queue is empty")
        return self._get()

    def _put(self, val):
        self._evput.set()
        self._evput.clear()
        self._queue.append(val)

    async def put(self, val):
        while self.full():
            await self._evget.wait()
        self._put(val)

    def put_nowait(self, val):
        if self.full():
            raise Exception("Cannot put item, queue is full")
        self._put(val)

    def qsize(self):
        return len(self._queue)

    def empty(self):
        return len(self._queue) == 0

    def full(self):
        return self.maxsize > 0 and len(self._queue) >= self.maxsize

