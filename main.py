def u16(n):
    return int(n).to_bytes(2, "big")

def u32(n):
    return int(n).to_bytes(4, "big")

def wrap(payload: bytes) -> bytes:
    data = u16(len(payload)) + payload
    out = bytearray([0x01])

    for b in data:
        if 0x00 < b < 0x04:
            out += bytes([0x02, b ^ 0x04])
        else:
            out.append(b)

    out.append(0x03)
    return bytes(out)

def unwrap(packet: bytes) -> bytes:
    if packet and packet[0] == 0x01 and packet[-1] == 0x03:
        packet = packet[1:-1]

    out = bytearray()
    i = 0

    while i < len(packet):
        if packet[i] == 0x02 and i + 1 < len(packet):
            out.append(packet[i + 1] ^ 0x04)
            i += 2
        else:
            out.append(packet[i])
            i += 1

    return bytes(out[2:]) if len(out) >= 2 else bytes(out)

def xor_checksum(data: bytes) -> int:
    x = 0
    for b in data:
        x ^= b
    return x & 0xFF

def make_chunk_packet(compressed, chunk_index, chunk):
    body = b"\x00"
    body += u32(len(compressed))
    body += u16(chunk_index)
    body += u16(len(chunk))
    body += chunk
    body += bytes([xor_checksum(body)])
    return wrap(b"\x03" + body)

def chunks(data, size=1024):
    for i in range(0, len(data), size):
        yield data[i:i + size]

async def wait_for_ack(kind, chunk_index=None, timeout=5.0):
    while True:
        payload = await asyncio.wait_for(ack_queue.get(), timeout=timeout)
        if DEBUG: print(repr(payload))
        if kind == "login" and len(payload) >= 2 and payload[0] == 0x0D and payload[-1] == 0:
            return payload

        if kind == "start" and len(payload) >= 2 and payload[0] == 0x02:
            return payload

        if kind == "chunk" and len(payload) >= 5 and payload[0] == 0x03:
            idx = (payload[2] << 8) | payload[3]
            status = payload[4]

            if idx == chunk_index:
                if status != 0:
                    raise RuntimeError(f"chunk {chunk_index} error {status}")

                return payload

async def write_ble_packet(characteristic, payload: bytes, chunk_size: int = 180, silent=BLE_SILENT):
    """Writes bytes using response=False (matching your characteristic property)."""
    if not silent:
        if DEBUG: print(f"[TX] Writing {len(payload)} bytes: {payload.hex()}")
    for i in range(0, len(payload), chunk_size):
        chunk = payload[i : i + chunk_size]
        await characteristic.write(chunk, response=False)
        await asyncio.sleep(0.01)
    if not silent:
        if DEBUG: print("[TX] Write complete.")

async def ble_notification_listener(characteristic):
    """
    Listens for notifications on an already-discovered characteristic 
    and pushes data directly into ack_queue via put_nowait().
    """
    try:
        # Enable notifications on the characteristic
        await characteristic.subscribe(notify=True)
        if DEBUG: print(f"Subscribed to {characteristic.uuid}")

        while True:
            data = await characteristic.notified()
            payload = unwrap(data)
            try:
                ack_queue.put_nowait(payload)
            except asyncio.QueueFull:
                # Handle queue overflow (e.g., drop oldest item to make space)
                _ = ack_queue.get_nowait()
                ack_queue.put_nowait(payload)

    except asyncio.CancelledError:
        if DEBUG: print("Listener task cancelled.")
    except Exception as e:
        if DEBUG: print(f"Error in notification listener: {e}")

